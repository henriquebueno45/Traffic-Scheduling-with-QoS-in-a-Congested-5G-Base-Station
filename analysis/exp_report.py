"""Statistics and verdicts for hypotheses H1 through H6 in experiments E1 through E5.

Reads results/exp/E*_raw.csv (generated by analysis.experiments) and writes:
  *_table.csv, E*_*.png, and verdict.csv (one row per hypothesis and its pre-registration rule).

All comparisons are paired by seed; 95% CI = 2000-resample bootstrap of mean differences.
Decision rules: results/EXPERIMENTS.md.

Usage: python -m analysis.exp_report [E1 E2 ...]
"""
from __future__ import annotations

import os
import sys

import matplotlib
import numpy as np
import pandas as pd

from analysis.sweep import ROOT

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OUT = ROOT / "results" / "exp"
SLA = 0.99
POLS = ["fifo", "prio", "edf", "dwrr", "prio_floor"]
SCENS = ["fixed", "L1", "L2", "L4"]
RNG = np.random.default_rng(0)


# ---------------------------------------------------------------- statistics
def boot_ci(x, n_boot: int = 2000) -> tuple[float, float, float]:
    """Return (mean, lower bound, upper bound) using a 95% bootstrap percentile interval."""
    v = np.asarray(x, dtype=float)
    v = v[~np.isnan(v)]
    if len(v) == 0:
        return (np.nan,) * 3
    m = RNG.choice(v, size=(n_boot, len(v)), replace=True).mean(axis=1)
    return float(v.mean()), *map(float, np.percentile(m, [2.5, 97.5]))


def paired_ci(a: pd.Series, b: pd.Series) -> tuple[float, float, float]:
    """Confidence interval for the mean of (a - b), paired by seed index."""
    j = pd.concat([a, b], axis=1, join="inner").dropna()
    return boot_ci((j.iloc[:, 0] - j.iloc[:, 1]).to_numpy())


def sla_capacity(loads: np.ndarray, m: np.ndarray, thr: float = SLA) -> tuple[float, str]:
    """Load where min(QoS voice, QoS video) crosses `thr` by linear interpolation.

    Returns (capacity, status): 'ok', 'left' (violates at the lowest load), or
    'right' (never violates; censored at the highest load).
    """
    if m[0] < thr:
        return float(loads[0]), "left"
    for i in range(1, len(loads)):
        if m[i] < thr:
            x = loads[i - 1] + (m[i - 1] - thr) / (m[i - 1] - m[i]) * (loads[i] - loads[i - 1])
            return float(x), "ok"
    return float(loads[-1]), "right"


def load_raw(exp: str, trim: str = "trim") -> pd.DataFrame:
    df = pd.read_csv(OUT / f"{exp}_raw.csv")
    return df[df["trim"] == trim]


def verdict(rows: list, h: str, rule: str, supported: bool | None, detail: str) -> None:
    rows.append({"hypothesis": h, "rule": rule,
                 "verdict": {True: "SUPPORTED", False: "REFUTED", None: "INCONCLUSIVE"}[supported],
                 "detail": detail})


# ---------------------------------------------------------------- E1 (H1, H2)
def report_e1(ver: list) -> None:
    d = load_raw("E1")
    q = d.pivot_table(index=["scen", "policy", "seed", "load"], columns="class", values="qos")
    q["m"] = q[["voice", "video"]].min(axis=1)
    rows = []
    for (sc, pol, seed), g in q.groupby(level=[0, 1, 2]):
        g = g.reset_index().sort_values("load")
        cap, st = sla_capacity(g["load"].to_numpy(), g["m"].to_numpy())
        rows.append({"scen": sc, "policy": pol, "seed": seed, "cap": cap, "status": st})
    cap = pd.DataFrame(rows)
    cap.to_csv(OUT / "E1_capacity_per_seed.csv", index=False)

    summ = []
    for (sc, pol), g in cap.groupby(["scen", "policy"]):
        m, lo, hi = boot_ci(g["cap"])
        summ.append({"scen": sc, "policy": pol, "C_SLA": m, "lo": lo, "hi": hi, "n": len(g),
                     "right_censored": int((g["status"] == "right").sum()),
                     "left_censored": int((g["status"] == "left").sum())})
    summ = pd.DataFrame(summ)
    summ.to_csv(OUT / "E1_capacity_table.csv", index=False)
    print("\nE1: capacity under SLA (relative load)\n",
          summ.pivot(index="policy", columns="scen", values="C_SLA").round(2).to_string())
    print(summ[(summ.right_censored > 0) | (summ.left_censored > 0)].to_string(index=False))

    # H1: L4 - L1 for each policy, paired by seed
    cs = cap.set_index(["policy", "scen", "seed"])["cap"]
    h1, det = [], []
    for pol in POLS:
        m, lo, hi = paired_ci(cs[pol]["L4"], cs[pol]["L1"])
        h1.append(lo > 0)
        det.append(f"{pol}: {m:+.2f} [{lo:+.2f}; {hi:+.2f}]")
    verdict(ver, "H1", "95% CI of C_SLA(L4)-C_SLA(L1) > 0 for every policy", all(h1), "; ".join(det))

    # H2: policy gain (prio - fifo, L1) versus diversity gain (fifo L4 - L1)
    pol_gain = cs["prio"]["L1"] - cs["fifo"]["L1"]
    div_gain = cs["fifo"]["L4"] - cs["fifo"]["L1"]
    mp, lp, hp = boot_ci(pol_gain)
    md, ld, hd = boot_ci(div_gain)
    mdd, ldd, hdd = paired_ci(pol_gain, div_gain)
    verdict(ver, "H2", "descriptive comparison of policy and diversity gains (L=1)", None,
            f"policy(prio-fifo)={mp:+.2f} [{lp:+.2f};{hp:+.2f}]; "
            f"diversity(fifo L4-L1)={md:+.2f} [{ld:+.2f};{hd:+.2f}]; "
            f"difference={mdd:+.2f} [{ldd:+.2f};{hdd:+.2f}]")

    fig, ax = plt.subplots(figsize=(7, 3.8))
    w = 0.2
    for i, sc in enumerate(SCENS):
        s = summ[summ.scen == sc].set_index("policy").reindex(POLS)
        ax.bar(np.arange(len(POLS)) + (i - 1.5) * w, s["C_SLA"], w,
               yerr=[s["C_SLA"] - s["lo"], s["hi"] - s["C_SLA"]], capsize=2, label=sc)
    ax.set_xticks(range(len(POLS)), POLS)
    ax.set_ylabel("capacity under SLA (relative load)")
    ax.set_ylim(1.0, 2.5)
    ax.axhline(1.56, color="gray", lw=0.7, ls="--")
    ax.legend(title="channel (mean 50 PRB)", fontsize=7)
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT / "E1_capacity.png", dpi=150)

    fig, axes = plt.subplots(1, 4, figsize=(14, 3.4), sharey=True)
    for ax, sc in zip(axes, SCENS):
        for pol in POLS:
            g = q.xs((sc, pol), level=[0, 1]).reset_index().groupby("load")["m"]
            mm = g.mean()
            ci = g.apply(lambda x: boot_ci(x)[1:])
            ax.errorbar(mm.index, mm.values,
                        yerr=[mm.values - [c[0] for c in ci], [c[1] for c in ci] - mm.values],
                        marker="o", ms=3, capsize=2, label=pol)
        ax.axhline(SLA, color="k", lw=0.7, ls="--")
        ax.set_title(sc)
        ax.set_xlabel("relative load")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("min(QoS voice, QoS video)")
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "E1_qos_vs_load.png", dpi=150)


# ---------------------------------------------------------------- E2 (H3)
def report_e2(ver: list) -> None:
    d = load_raw("E2")
    d["cfg"] = d["floor_video"].astype(str) + "/" + d["floor_data"].astype(str)
    key = ["scen", "load", "cfg"]
    rows = []
    for k, g in d.groupby(key):
        r = dict(zip(key, k))
        for c in ("voice", "video", "data"):
            gc = g[g["class"] == c]
            r[f"qos_{c}"] = gc["qos"].mean()
        gd = g[g["class"] == "data"]
        r["data_thr_prb_s"] = gd["throughput_prb_s"].mean()
        r["data_starve_max_ms"] = gd["max_starve_ms"].max()
        r["data_starve_med_ms"] = gd["max_starve_ms"].median()
        rows.append(r)
    t = pd.DataFrame(rows)
    t.to_csv(OUT / "E2_table.csv", index=False)
    pd.set_option("display.width", 220)
    print("\nE2: minimum floor\n", t.round(3).to_string(index=False))

    ok, det = [], []
    for (sc, ld), g in d.groupby(["scen", "load"]):
        base = g[g["cfg"] == "0/0"]
        for fd in (1, 2):
            cur = g[g["cfg"] == f"0/{fd}"]
            starve_ok = cur[cur["class"] == "data"]["max_starve_ms"].max() <= 1.0
            costs = []
            for c in ("voice", "video"):
                a = cur[cur["class"] == c].set_index("seed")["qos"]
                b = base[base["class"] == c].set_index("seed")["qos"]
                m, lo, hi = paired_ci(a, b)
                costs.append((c, m, lo, hi))
            cost_ok = all(lo >= -0.01 and hi <= 0.01 for _, _, lo, hi in costs)
            ok.append(starve_ok and cost_ok)
            det.append(f"{sc} {ld}x floor={fd}: starvation<=1ms={starve_ok}; "
                       + ", ".join(f"Δ{c}={m:+.3f}[{lo:+.3f};{hi:+.3f}]" for c, m, lo, hi in costs))
    verdict(ver, "H3", "1-2 PRB/slot floor: data starvation <=1 ms (all seeds) and |ΔQoS voice/video|<=0.01",
            all(ok), " | ".join(det))

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.5))
    for ax, ld in zip(axes, (1.6, 2.0)):
        for sc, mk in (("fixed", "o"), ("L1", "s")):
            g = t[(t.scen == sc) & (t.load == ld) & t.cfg.str.startswith("0/")]
            g = g.sort_values("cfg", key=lambda s: s.str.split("/").str[1].astype(int))
            fd = g["cfg"].str.split("/").str[1].astype(int)
            ax.plot(fd, g["qos_video"], mk + "-", label=f"video {sc}")
            ax.plot(fd, g["qos_voice"], mk + "--", label=f"voice {sc}")
        ax.set_title(f"load {ld}x")
        ax.set_xlabel("data floor (PRB/slot)")
        ax.set_ylabel("QoS")
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "E2_floor.png", dpi=150)


# ---------------------------------------------------------------- E3 (H4)
def report_e3(ver: list) -> None:
    d = load_raw("E3")
    v = d[d["class"] == "voice"]
    t = v.groupby(["load", "stagger", "policy"])["qos"].mean().unstack("policy")
    t.to_csv(OUT / "E3_table.csv")
    print("\nE3: voice QoS by K (sub-bursts)\n", t.round(3).to_string())
    flips = []
    for ld, g in v.groupby("load"):
        pq = g.pivot_table(index=["stagger", "seed"], columns="policy", values="qos")
        pols = list(pq.columns)
        for i, a in enumerate(pols):
            for b in pols[i + 1:]:
                s1 = np.sign(paired_ci(pq.loc[1][a], pq.loc[1][b])[0])
                for k in sorted(pq.index.get_level_values(0).unique()):
                    m, lo, hi = paired_ci(pq.loc[k][a], pq.loc[k][b])
                    if s1 != 0 and np.sign(m) == -s1 and (lo > 0 or hi < 0):
                        flips.append(f"{ld}x K={k}: {a}-{b}={m:+.3f}[{lo:+.3f};{hi:+.3f}]")
    verdict(ver, "H4", "policy order (voice QoS) equals K=1 for every K; a swap with CI excluding zero refutes H4",
            not flips, "no significant policy swaps" if not flips else "; ".join(flips))

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4), sharey=True)
    for ax, ld in zip(axes, (1.5, 1.8)):
        for pol in ("fifo", "prio", "edf", "dwrr"):
            g = v[(v.load == ld) & (v.policy == pol)].groupby("stagger")["qos"]
            m = g.mean()
            ci = np.array([boot_ci(x)[1:] for _, x in g])
            ax.errorbar(m.index, m.values, yerr=[m.values - ci[:, 0], ci[:, 1] - m.values],
                        marker="o", capsize=2, label=pol)
        ax.set_xscale("log")
        ax.set_title(f"load {ld}x")
        ax.set_xlabel("K (sub-bursts per period)")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("voice QoS")
    axes[0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "E3_bursts.png", dpi=150)


# ---------------------------------------------------------------- E4 (H6)
def report_e4(ver: list) -> None:
    d = pd.read_csv(OUT / "E4_raw.csv")
    d["variant"] = d["duration"].astype(int).astype(str) + "s/" + d["trim"]
    t = d.pivot_table(index=["policy", "load", "class"], columns="variant", values="qos")
    t.to_csv(OUT / "E4_table.csv")
    print("\nE4: QoS by measurement variant\n", t.round(3).to_string())
    ref = "20s/trim"
    hit, det = [], []
    for (pol, ld, c), _ in t.iterrows():
        g = d[(d.policy == pol) & (d.load == ld) & (d["class"] == c)]
        a = g[g.variant == "4s/none"].set_index("seed")["qos"]
        b = g[g.variant == ref].set_index("seed")["qos"]
        m, lo, hi = paired_ci(a, b)
        if abs(m) > 0.01 and (lo > 0 or hi < 0):
            hit.append(True)
            det.append(f"{pol} {ld}x {c}: {m:+.3f}[{lo:+.3f};{hi:+.3f}]")
    ordens = []
    for var in ("4s/none", ref):
        for ld in (1.8, 2.0):
            s = t.xs(ld, level="load").xs("voice", level="class")[var]
            ordens.append(f"{var} {ld}x voice: " + ">".join(s.sort_values(ascending=False).index))
    verdict(ver, "H6", "|QoS(4s no trim)-QoS(20s trim)|>0.01 with a non-zero CI in at least one policy/load/class combination",
            bool(hit), ("; ".join(det[:8]) or "no relevant difference") + " || " + "; ".join(ordens))


# ---------------------------------------------------------------- E5 (H5)
def report_e5(ver: list) -> None:
    d = load_raw("E5")
    v = d[d["class"] == "voice"]
    t = v.groupby(["policy", "load", "speed"])["qos"].mean().unstack("speed")
    t.to_csv(OUT / "E5_table.csv")
    print("\nE5: voice QoS versus speed (m/s)\n", t.round(3).to_string())
    g = v[(v.policy == "prio") & (v.load == 1.5)].pivot_table(index="seed", columns="speed", values="qos")
    m, lo, hi = paired_ci(g[30.0], g[0.3])
    verdict(ver, "H5", "95% CI of voice_QoS(30 m/s)-voice_QoS(0.3 m/s) > 0 (prio, 1.5x, L=1)", lo > 0,
            f"{m:+.3f} [{lo:+.3f}; {hi:+.3f}]")

    fig, ax = plt.subplots(figsize=(6, 3.6))
    for (pol, ld), grp in v.groupby(["policy", "load"]):
        s = grp.groupby("speed")["qos"]
        mm = s.mean()
        ci = np.array([boot_ci(x)[1:] for _, x in s])
        ax.errorbar(mm.index, mm.values, yerr=[mm.values - ci[:, 0], ci[:, 1] - mm.values],
                    marker="o", capsize=2, label=f"{pol} {ld}x")
    ax.set_xscale("log")
    ax.set_xlabel("speed (m/s) [T_c ≈ 0.42/f_D; f_D = v·fc/c]")
    ax.set_ylabel("Voice QoS (Rayleigh L=1, mean 50 PRB)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(OUT / "E5_speed.png", dpi=150)


# ---------------------------------------------------------------- E6 (exploratory)
def report_e6(ver: list) -> None:
    """Exploratory (not pre-registered): effect of log-normal shadowing on SLA capacity."""
    d = load_raw("E6")
    q = d.pivot_table(index=["scen", "policy", "shadow_db", "seed", "load"], columns="class",
                      values="qos")
    q["m"] = q[["voice", "video"]].min(axis=1)
    rows = []
    for (sc, pol, sh, seed), g in q.groupby(level=[0, 1, 2, 3]):
        g = g.reset_index().sort_values("load")
        cap, st = sla_capacity(g["load"].to_numpy(), g["m"].to_numpy())
        rows.append({"scen": sc, "policy": pol, "shadow_db": sh, "seed": seed, "cap": cap,
                     "status": st})
    cap = pd.DataFrame(rows)
    # Shadowing changes each trace's mean PRBs, so also report capacity normalised by the mean
    # PRBs actually offered by that seed's trace (the channel trace is deterministic per seed)
    from analysis.experiments import TARGET_MEAN_PRBS, equal_mean_distance
    from channel.channel_model import ChannelConfig, generate_prbs
    dist = {f"L{L}": equal_mean_distance(L) for L in (1, 4)}
    mean_prbs = {}
    for sc, sh, seed in cap[["scen", "shadow_db", "seed"]].drop_duplicates().itertuples(index=False):
        cfg = ChannelConfig(distance_m=dist[sc], antennas=int(sc[1:]), speed_mps=1.5,
                            shadow_sigma_db=sh)
        mean_prbs[(sc, sh, seed)] = float(generate_prbs(6016, cfg, int(seed)).mean())
    cap["mean_prbs"] = [mean_prbs[(a, b, c)] for a, b, c in zip(cap.scen, cap.shadow_db, cap.seed)]
    cap["cap_norm"] = cap["cap"] * TARGET_MEAN_PRBS / cap["mean_prbs"]
    cap.to_csv(OUT / "E6_capacity_per_seed.csv", index=False)
    summ = []
    for (sc, pol, sh), g in cap.groupby(["scen", "policy", "shadow_db"]):
        m, lo, hi = boot_ci(g["cap"])
        q05, q50, q95 = np.percentile(g["cap"], [5, 50, 95])
        mn, nlo, nhi = boot_ci(g["cap_norm"])
        summ.append({"scen": sc, "policy": pol, "shadow_db": sh, "C_SLA": m, "lo": lo, "hi": hi,
                     "std": g["cap"].std(), "q05": q05, "q50": q50, "q95": q95,
                     "C_norm": mn, "norm_lo": nlo, "norm_hi": nhi,
                     "mean_prbs": g["mean_prbs"].mean(), "n": len(g),
                     "left_censored": int((g["status"] == "left").sum()),
                     "right_censored": int((g["status"] == "right").sum())})
    summ = pd.DataFrame(summ)
    summ.to_csv(OUT / "E6_table.csv", index=False)
    print("\nE6 (exploratory): capacity under SLA with and without shadowing\n",
          summ.round(3).to_string(index=False))
    for col, lab in (("cap", "C_SLA"), ("cap_norm", "C_SLA per mean PRB")):
        cs = cap.set_index(["policy", "scen", "shadow_db", "seed"])[col]
        for pol in ("fifo", "prio"):
            for sc in ("L1", "L4"):
                m, lo, hi = paired_ci(cs[pol][sc][6.0], cs[pol][sc][0.0])
                print(f"  paired change in {lab} from shadowing, {pol} {sc}: "
                      f"{m:+.2f} [{lo:+.2f}; {hi:+.2f}]")
    cs = cap.set_index(["policy", "scen", "shadow_db", "seed"])["cap_norm"]
    for sh in (0.0, 6.0):
        for sc in ("L1", "L4"):
            m, lo, hi = paired_ci(cs["prio"][sc][sh], cs["fifo"][sc][sh])
            print(f"  prio - fifo (normalised), {sc}, sigma={sh:g}: {m:+.2f} [{lo:+.2f}; {hi:+.2f}]")
    for sh in (0.0, 6.0):
        for pol in ("fifo", "prio"):
            m, lo, hi = paired_ci(cs[pol]["L4"][sh], cs[pol]["L1"][sh])
            print(f"  L4 - L1 (normalised), {pol}, sigma={sh:g}: {m:+.2f} [{lo:+.2f}; {hi:+.2f}]")

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, pol in zip(axes, ("fifo", "prio")):
        data, labels = [], []
        for sc in ("L1", "L4"):
            for sh in (0.0, 6.0):
                data.append(cap[(cap.policy == pol) & (cap.scen == sc)
                                & (cap.shadow_db == sh)]["cap_norm"].to_numpy())
                labels.append(f"{sc}\n{int(sh)} dB")
        ax.boxplot(data, tick_labels=labels, showmeans=True)
        ax.set_title(f"{pol}: per-seed SLA capacity / mean PRBs")
        ax.grid(axis="y", alpha=0.3)
    axes[0].set_ylabel("capacity under SLA (normalised to mean PRBs)")
    fig.tight_layout()
    fig.savefig(OUT / "E6_shadowing.png", dpi=150)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(os, "sched_setaffinity"):
        os.sched_setaffinity(0, {0, 4})
    exps = sys.argv[1:] or ["E1", "E2", "E3", "E4", "E5", "E6"]
    fns = {"E1": report_e1, "E2": report_e2, "E3": report_e3, "E4": report_e4, "E5": report_e5,
           "E6": report_e6}
    ver: list = []
    for e in exps:
        if (OUT / f"{e}_raw.csv").exists():
            fns[e](ver)
        else:
            print(f"{e}: no data")
    v = pd.DataFrame(ver)
    v.to_csv(OUT / "verdict.csv", index=False)
    pd.set_option("display.max_colwidth", 400)
    print("\n=== VERDICTS ===")
    for r in ver:
        print(f"{r['hypothesis']}: {r['verdict']}  ({r['rule']})\n    {r['detail']}")


if __name__ == "__main__":
    main()
